import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { parseArgs } from 'node:util'

import { Fetcher } from './http.ts'
import type { Group } from './inventory.ts'
import { crawlUrl, type Snapshot, type SnapshotRecord, toJson } from './snapshot.ts'

const ROOT = resolve(import.meta.dirname, '../..')
const DEFAULT_BASE = 'http://localhost:8787'
const BEFORE = 'docs/before/seo-snapshot.json'
const REDIRECT_MAP = 'docs/redirect-map.csv'
const REPORT = 'docs/seo-parity-report.md'
const AFTER_SNAPSHOT = 'docs/after/seo-snapshot.json'

const INTENDED: Readonly<Record<string, string>> = {
  '/': 'gains an H1 (the WordPress home had none)',
  '/about/': 'gains an H1 (the WordPress cover heading was an H2)',
  '/blog/': 'gains a real title and a meta description (WordPress had "Blog - Larchwick" and none)',
}
const META_GROUPS: ReadonlySet<Group> = new Set(['pages', 'posts'])

interface Check {
  group: Group
  path: string
  slashless: boolean
  expected: string | null
  record: SnapshotRecord
  problems: string[]
  notes: string[]
}

function readOptions(): { base: string } {
  const { values } = parseArgs({ options: { base: { type: 'string', default: DEFAULT_BASE } } })
  const base = (values.base ?? DEFAULT_BASE).replace(/\/+$/, '')
  if (!/^https?:\/\/[^/]+$/.test(base)) throw new Error(`--base must be an origin, got "${base}"`)
  return { base }
}

function readRedirectMap(): Map<string, string> {
  const rows = readFileSync(resolve(ROOT, REDIRECT_MAP), 'utf8').trim().split('\n').slice(1)
  return new Map(
    rows.map((row) => row.split(',') as [string, string]).map(([from, to]) => [from, to]),
  )
}

function expectedTarget(
  group: Group,
  path: string,
  map: ReadonlyMap<string, string>,
): string | null {
  switch (group) {
    case 'pages':
    case 'robots':
      return path
    case 'categories':
      return path.replace(/^\/category\//, '/blog/category/')
    case 'tags':
      return path.replace(/^\/tag\//, '/blog/tag/')
    case 'date-archives':
    case 'feeds':
      return '/blog/'
    case 'author':
      return '/about/'
    case 'sitemaps':
      return '/sitemap-index.xml'
    case 'shortlinks':
      return null
    default:
      return map.get(path) ?? null
  }
}

function pathOf(url: string | null): string | null {
  if (!url) return null
  try {
    return new URL(url, 'http://local').pathname
  } catch {
    return url
  }
}

function checkRecord(check: Check, before: SnapshotRecord): void {
  const { record, expected } = check
  if (expected === null) return
  if (record.finalStatus !== 200) check.problems.push(`final status ${record.finalStatus}`)
  if (pathOf(record.finalUrl) !== expected) {
    check.problems.push(`lands on ${record.finalUrl}, expected ${expected}`)
  }
  const allowedHops = expected === check.path && !check.slashless ? 0 : 1
  if (record.hops.length > allowedHops) check.problems.push(`${record.hops.length} hops`)
  for (const hop of record.hops) {
    if (hop.status !== 301) check.problems.push(`hop is ${hop.status}, not 301`)
  }
  if (check.slashless || !META_GROUPS.has(check.group)) return

  const intended = INTENDED[expected]
  if (intended) check.notes.push(intended)
  if (record.h1?.length !== 1) check.problems.push(`${record.h1?.length ?? 0} H1s`)
  if (pathOf(record.canonical) !== expected) check.problems.push(`canonical ${record.canonical}`)
  if (!record.title) check.problems.push('no title')
  if (!record.description) check.problems.push('no meta description')
  if (intended) return
  if (record.title !== before.title) check.problems.push(`title changed: "${record.title}"`)
  if (before.description && record.description !== before.description) {
    check.problems.push('description changed')
  }
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|')
}

function toMarkdown(checks: readonly Check[], base: string, date: string): string {
  const scored = checks.filter((check) => check.expected !== null)
  const failed = scored.filter((check) => check.problems.length > 0)
  const groups = [...new Set(scored.map((check) => check.group))]
  const shortlinks = checks.filter((check) => check.expected === null)
  const notes = scored.filter((check) => check.notes.length > 0)
  return [
    '# SEO parity report',
    '',
    `Generated by \`npm run seo:compare\` on ${date} against \`${base}\`. Every old WordPress URL`,
    `from \`${BEFORE}\` is requested in its recorded form and, where it ends in "/", without the`,
    'slash. Redirects must land on the expected page in one 301; pages and posts must keep their',
    'title and description, have one H1, and a canonical that matches the final URL.',
    '',
    `**Result: ${scored.length - failed.length} of ${scored.length} checks pass.**`,
    '',
    '## By group',
    '',
    '| Group | Checked | Pass | Fail |',
    '| --- | --- | --- | --- |',
    ...groups.map((group) => {
      const inGroup = scored.filter((check) => check.group === group)
      const bad = inGroup.filter((check) => check.problems.length > 0).length
      return `| ${group} | ${inGroup.length} | ${inGroup.length - bad} | ${bad} |`
    }),
    '',
    '## Failures',
    '',
    ...(failed.length === 0
      ? ['None.']
      : [
          '| Old URL | Problems |',
          '| --- | --- |',
          ...failed.map(
            (check) => `| \`${cell(check.record.path)}\` | ${cell(check.problems.join('; '))} |`,
          ),
        ]),
    '',
    '## Intended differences',
    '',
    ...notes.map((check) => `- \`${check.path}\`: ${check.notes.join('; ')}.`),
    '- Attachment pages now redirect to the page or post they belong to; WordPress sent them to the',
    '  image file.',
    '',
    '## Known limitation: shortlinks',
    '',
    "Cloudflare's `_redirects` can't match query strings, so `/?p=N` and `/?page_id=N` serve the home",
    'page (PLAN.md §12). Supporting them would need Worker code.',
    '',
    '| Old URL | Status | Lands on |',
    '| --- | --- | --- |',
    ...shortlinks.map(
      (check) =>
        `| \`${check.record.path}\` | ${check.record.finalStatus} | \`${check.record.finalUrl}\` |`,
    ),
    '',
  ].join('\n')
}

async function main(): Promise<void> {
  const { base } = readOptions()
  const before = JSON.parse(readFileSync(resolve(ROOT, BEFORE), 'utf8')) as Snapshot
  const map = readRedirectMap()
  const fetcher = new Fetcher(resolve(ROOT, '.cache/seo-check/after', new URL(base).host), false)
  const checks: Check[] = []
  console.log(`Comparing ${before.records.length} old URLs against ${base}`)
  for (const old of before.records) {
    const variants = [old.path]
    const slashless = old.path.length > 1 && old.path.endsWith('/') ? old.path.slice(0, -1) : null
    if (slashless) variants.push(slashless)
    for (const path of variants) {
      const record = await crawlUrl({ group: old.group, path }, base, fetcher)
      const check: Check = {
        group: old.group,
        path: old.path,
        slashless: path !== old.path,
        expected: expectedTarget(old.group, old.path, map),
        record,
        problems: [],
        notes: [],
      }
      checkRecord(check, old)
      checks.push(check)
    }
  }
  const date = new Date().toISOString().slice(0, 10)
  mkdirSync(resolve(ROOT, 'docs/after'), { recursive: true })
  writeFileSync(resolve(ROOT, REPORT), toMarkdown(checks, base, date))
  const after = { crawledAt: date, base, records: checks.map((check) => check.record) }
  writeFileSync(resolve(ROOT, AFTER_SNAPSHOT), toJson(after))
  const failed = checks.filter((check) => check.problems.length > 0)
  for (const check of failed)
    console.log(`  FAIL ${check.record.path}: ${check.problems.join('; ')}`)
  const scored = checks.filter((check) => check.expected !== null).length
  console.log(`${scored - failed.length}/${scored} checks pass`)
  console.log(`Wrote ${REPORT} and ${relative(ROOT, join(ROOT, AFTER_SNAPSHOT))}`)
  if (failed.length > 0) process.exitCode = 1
}

await main()
