import { escapeCell } from '../shared/markdown.ts'
import type { Built, Group } from './documents.ts'
import type { MutationPlan } from './sync.ts'

export interface MediaSummary {
  total: number
  existing: number
  uploaded: number
  pending: number
  missingAlt: number[]
}

export interface Report {
  mode: 'dry run' | 'write'
  date: string
  source: string
  target: string
  media: MediaSummary
  documents: Record<Group, { total: number; create: number; patch: number; unchanged: number }>
  mutations: number
  warnings: Built['warnings']
  links: Built['links']
  redirects: number
  skipped: Built['skipped']
}

export function summarise(
  built: Built,
  plan: MutationPlan,
  base: Omit<Report, 'documents' | 'mutations' | 'warnings' | 'links' | 'redirects' | 'skipped'>,
): Report {
  const documents = {} as Report['documents']
  for (const { group, doc } of built.docs) {
    const row = (documents[group] ??= { total: 0, create: 0, patch: 0, unchanged: 0 })
    row.total += 1
    const mutation = plan.mutations.find((item) => item.id === doc._id)
    if (!mutation) row.unchanged += 1
    else row[mutation.kind] += 1
  }
  return {
    ...base,
    documents,
    mutations: plan.mutations.length,
    warnings: built.warnings,
    links: built.links,
    redirects: built.redirects.length,
    skipped: built.skipped,
  }
}

export function toMarkdown(report: Report): string {
  const lines = [
    '# WordPress import report',
    '',
    `Generated by \`npm run import:wp\` (${report.mode}) on ${report.date}.`,
    `Source: \`${report.source}\`. Target: Sanity ${report.target}.`,
    '',
    '## Documents',
    '',
    '| Group | Documents | Create | Patch | Unchanged |',
    '| --- | --- | --- | --- | --- |',
    ...Object.entries(report.documents).map(
      ([group, row]) =>
        `| ${group} | ${row.total} | ${row.create} | ${row.patch} | ${row.unchanged} |`,
    ),
    '',
    `**Mutations: ${report.mutations}.** A re-run of an unchanged import reports 0.`,
    '',
    '## Media',
    '',
    `- ${report.media.total} WordPress images: ${report.media.existing} already in Sanity, ${report.media.uploaded} uploaded, ${report.media.pending} not uploaded yet${report.mode === 'dry run' ? ' (dry run)' : ''}.`,
    `- Missing alt text: ${report.media.missingAlt.length === 0 ? 'none' : report.media.missingAlt.join(', ')}.`,
    '',
    '## Skipped',
    '',
    ...(report.skipped.length === 0
      ? ['Nothing.']
      : report.skipped.map((item) => `- ${item.where}: ${item.reason}`)),
    '',
    '## Warnings',
    '',
    ...(report.warnings.length === 0
      ? ['None.']
      : report.warnings.map((item) => `- ${item.where}: ${item.message}`)),
    '',
    '## Rewritten links',
    '',
    ...(report.links.length === 0
      ? ['None.']
      : [
          '| Where | From | To | Why |',
          '| --- | --- | --- | --- |',
          ...report.links.map(
            (link) =>
              `| ${escapeCell(link.where)} | \`${escapeCell(link.from)}\` | \`${escapeCell(link.to)}\` | ${link.reason} |`,
          ),
        ]),
    '',
    '## Redirects',
    '',
    `${report.redirects} redirect documents. The full list is in [redirect-map.csv](./redirect-map.csv). Pattern rules (categories, tags, dates, feeds, author, sitemaps) live in code (Phase 6).`,
    '',
  ]
  return lines.join('\n')
}

export function toCsv(rows: Built['redirects']): string {
  const quote = (value: string) => (/[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value)
  return [
    'old,new,status,reason',
    ...rows.map((row) => [row.from, row.to, String(row.status), row.reason].map(quote).join(',')),
    '',
  ].join('\n')
}
